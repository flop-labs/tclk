#!/usr/bin/env node
// SPDX-License-Identifier: Apache-2.0
// Generate the decoder's field contract and SPEC table from the tclk/1 JSON Schema.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const schemaPath = join(root, "schema/tclk1-frames.schema.json");
const generatedPath = join(root, "src/frame-fields.generated.ts");
const specPath = join(root, "SPEC.md");
const schema = JSON.parse(readFileSync(schemaPath, "utf8"));
const frameNames = schema.oneOf.map((entry) => entry.$ref.split("/").at(-1));

const fields = Object.fromEntries(frameNames.map((name) => {
  const definition = schema.$defs[name];
  return [name, {
    allowed: Object.keys(definition.properties),
    required: definition.required,
  }];
}));

const generated = `// SPDX-License-Identifier: Apache-2.0\n` +
  `// Generated by scripts/generate-frame-fields.mjs from schema/tclk1-frames.schema.json.\n` +
  `// Do not edit by hand.\n\n` +
  `export const FRAME_FIELDS = ${JSON.stringify(fields, null, 2)} as const;\n\n` +
  `export const TCLK1_RAIL_PATTERN = ${JSON.stringify(schema.$defs.rail.pattern)};\n` +
  `export const CANONICAL_RAIL_ID_PATTERN = ${JSON.stringify(schema.$defs.rail["x-tclk-canonicalPattern"])};\n\n` +
  `export const CANONICAL_RAIL_IDS = ${JSON.stringify(schema.$defs.rail["x-tclk-canonicalIds"], null, 2)} as const;\n\n` +
  `export const RAIL_ID_ALIASES = ${JSON.stringify(schema.$defs.rail["x-tclk-aliases"], null, 2)} as const;\n`;

// A required field the sender computes rather than supplies reads, in a list beside five it can
// copy, like one more thing to fill in — and it is the one that gets left out. Mark it in the
// table, since the table is what implementers write their frames from.
const derived = Object.fromEntries(frameNames.map((name) => [
  name,
  Object.entries(schema.$defs[name].properties)
    .filter(([, property]) => property["x-tclk-derived"])
    .map(([field]) => field),
]));
const anyDerived = frameNames.some((name) => derived[name].length > 0);

const rows = frameNames.map((name) => {
  const definition = fields[name];
  const required = definition.required
    .map((field) => derived[name].includes(field) ? `\`${field}\`&nbsp;†` : `\`${field}\``)
    .join(", ");
  const optionalFields = definition.allowed.filter((field) => !definition.required.includes(field));
  const optional = optionalFields.length === 0
    ? "—"
    : optionalFields.map((field) => `\`${field}\``).join(", ");
  return `| \`${name}\` | ${required} | ${optional} |`;
});
const table = [
  "<!-- BEGIN GENERATED FRAME FIELDS -->",
  "| frame | required fields | optional fields |",
  "|---|---|---|",
  ...rows,
  ...(anyDerived
    ? [
      "",
      "† Derived, not supplied. The sending side computes it from frames that are already public;"
      + " it is never a value the counterparty fills in later. A frame that omits it is rejected at"
      + " decode, before it is signed, posted, or used to advance state.",
    ]
    : []),
  "<!-- END GENERATED FRAME FIELDS -->",
].join("\n");

const spec = readFileSync(specPath, "utf8");
const nextSpec = spec.replace(
  /<!-- BEGIN GENERATED FRAME FIELDS -->[\s\S]*?<!-- END GENERATED FRAME FIELDS -->/,
  table,
);
if (nextSpec === spec && !spec.includes(table)) {
  throw new Error("SPEC.md has no generated frame-field markers");
}

if (process.argv.includes("--check")) {
  if (readFileSync(generatedPath, "utf8") !== generated || spec !== nextSpec) {
    console.error("generated protocol fields are stale; run pnpm generate:protocol");
    process.exit(1);
  }
} else {
  writeFileSync(generatedPath, generated);
  writeFileSync(specPath, nextSpec);
}
